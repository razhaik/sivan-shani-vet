function escapeHtml(value: unknown): string {
  return String(value ?? "").replace(/[&<>"']/g, (character) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;",
  }[character] || character));
}

export const CLINIC_EMAIL_LOGO_URL = VETERINARY_CLINIC_PROFILE.emailLogoUrl;

function safeCssColor(value: unknown, fallback: string): string {
  const color = typeof value === "string" ? value.trim() : "";
  return /^#[0-9a-fA-F]{6}$/.test(color) ? color : fallback;
}

/** Only links generated by the app are allowed to become customer email buttons. */
function safeActionUrl(value: unknown): string {
  return safePublicLink(value, VETERINARY_CLINIC_PROFILE);
}

function multilineHtml(value: unknown): string {
  return escapeHtml(value).replace(/\r?\n/g, "<br />");
}

function marketingDetailsHtml(details: MarketingEmailDetail[]): string {
  const visibleDetails = details.filter((detail) => detail && String(detail.label || "").trim());
  if (!visibleDetails.length) return "";
  return `
    <table role="presentation" width="100%" cellspacing="0" cellpadding="0" style="border-collapse:separate;border-spacing:0;background:rgba(244,249,250,0.82);border:1px solid #dce9ee;border-radius:16px;overflow:hidden;">
      ${visibleDetails.map((detail, index) => `
        <tr>
          <td style="padding:11px 14px;${index < visibleDetails.length - 1 ? "border-bottom:1px solid #dce9ee;" : ""}width:36%;vertical-align:top;color:#718792;font-size:11px;font-weight:800;">${escapeHtml(detail.label)}</td>
          <td style="padding:11px 14px;${index < visibleDetails.length - 1 ? "border-bottom:1px solid #dce9ee;" : ""}vertical-align:top;color:#0f2842;font-size:13px;font-weight:800;line-height:1.65;white-space:pre-wrap;word-break:break-word;">${multilineHtml(detail.value)}</td>
        </tr>
      `).join("")}
    </table>
  `;
}

function marketingActionsHtml(actions: MarketingEmailAction[]): string {
  const visibleActions = actions
    .map((action) => ({ ...action, url: safeActionUrl(action?.url) }))
    .filter((action) => action.url && String(action.label || "").trim())
    .slice(0, 2);
  if (!visibleActions.length) return "";

  return `
    <table role="presentation" width="100%" cellspacing="0" cellpadding="0" style="margin-top:25px;">
      <tr><td align="center">
        ${visibleActions.map((action) => {
          const background = action.variant === "danger" ? "#b83b4b" : action.variant === "secondary" ? "#0f2842" : "#1d6472";
          return `<a href="${escapeHtml(action.url)}" target="_blank" rel="noopener noreferrer" style="display:inline-block;margin:0 4px 8px;padding:12px 22px;border-radius:12px;background:${background};color:#ffffff;text-decoration:none;font-size:13px;font-weight:900;line-height:1.2;">${escapeHtml(action.label)}</a>`;
        }).join("")}
      </td></tr>
    </table>
  `;
}

